#!/usr/bin/env python3
"""Generate rom/logo_data.h from the V12 logo PNG."""

from __future__ import annotations

import argparse
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
TARGET_WIDTH = 360


def generate(source: Path, output: Path) -> None:
    image = Image.open(source).convert("RGBA")
    height = round(image.height * TARGET_WIDTH / image.width)
    alpha = image.resize((TARGET_WIDTH, height), Image.Resampling.LANCZOS).getchannel("A")

    runs: list[tuple[int, int, int]] = []
    for y in range(height):
        start: int | None = None
        for x in range(TARGET_WIDTH + 1):
            visible = x < TARGET_WIDTH and alpha.getpixel((x, y)) >= 64
            if visible and start is None:
                start = x
            elif not visible and start is not None:
                runs.append((start, x, y))
                start = None

    lines = [
        "/* Auto-generated by tools/gen_fancy.py. */",
        "#ifndef PPSSPP_FANCY_LOGO_DATA_H",
        "#define PPSSPP_FANCY_LOGO_DATA_H",
        "",
        f"#define LOGO_WIDTH {TARGET_WIDTH}",
        f"#define LOGO_HEIGHT {height}",
        f"#define LOGO_RUN_COUNT {len(runs)}",
        "",
        "typedef struct {",
        "    unsigned short x1, x2, y;",
        "} LogoRun;",
        "",
        "static const LogoRun kLogoRuns[LOGO_RUN_COUNT] = {",
    ]
    lines.extend(f"    {{{x1}, {x2}, {y}}}," for x1, x2, y in runs)
    lines.extend(("};", "", "#endif", ""))
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(lines))
    print(f"wrote {output} ({TARGET_WIDTH}x{height}, {len(runs)} horizontal runs)")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--logo", type=Path, default=ROOT / "fancy" / "v12_logo_black.png")
    parser.add_argument("--output", type=Path, default=ROOT / "rom" / "logo_data.h")
    args = parser.parse_args()
    generate(args.logo, args.output)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
